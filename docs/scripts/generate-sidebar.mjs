#!/usr/bin/env node
/**
 * Generate Starlight sidebar config from docs/site-nav.yaml.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const docsRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(docsRoot, "..");
const navPath = path.join(repoRoot, "docs", "site-nav.yaml");
const outputPath = path.join(docsRoot, "src/sidebar.generated.mjs");

function sourceToSlug(sourcePath) {
  if (sourcePath === "index.md") {
    return "index";
  }

  let stem = sourcePath.endsWith(".md") ? sourcePath.slice(0, -3) : sourcePath;
  if (stem.endsWith("/index")) {
    stem = stem.slice(0, -"/index".length);
  }
  if (!stem || stem === "index") {
    return "index";
  }

  return stem
    .split("/")
    .filter(Boolean)
    .map((segment) => segment.replace(/_/g, "-"))
    .join("/");
}

function navEntryToSidebar(entry) {
  if (typeof entry !== "object" || !entry) {
    return null;
  }

  for (const [label, value] of Object.entries(entry)) {
    if (typeof value === "string") {
      const slug = sourceToSlug(value);
      if (slug === "index") {
        return { label, link: "/" };
      }
      return { label, slug };
    }

    if (Array.isArray(value)) {
      const items = value.map(navEntryToSidebar).filter(Boolean);
      return { label, items };
    }
  }

  return null;
}

function buildSidebar(nav) {
  return (Array.isArray(nav) ? nav : []).map(navEntryToSidebar).filter(Boolean);
}

const payload = yaml.load(fs.readFileSync(navPath, "utf8"));
const sidebar = buildSidebar(payload?.nav ?? []);

const fileContents = `// Generated by scripts/generate-sidebar.mjs — do not edit by hand.
/** @type {import('@astrojs/starlight/types').StarlightUserConfig['sidebar']} */
export const sidebar = ${JSON.stringify(sidebar, null, 2)};
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, fileContents, "utf8");
console.log(`Wrote ${path.relative(docsRoot, outputPath)} (${sidebar.length} top-level groups)`);
