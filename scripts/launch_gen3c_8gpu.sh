#!/usr/bin/env bash
# GEN3C: eight one-GPU workers, each loading the pipeline once per shard.
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
WORLD_ROOT="${WORLD_ROOT:-$(cd -- "$SCRIPT_DIR/.." && pwd)}"

export WORLDARENA_CHECKPOINT_ROOT="${GEN3C_CHECKPOINT_ROOT:-${WORLDARENA_CHECKPOINT_ROOT:-$WORLD_ROOT/../ckpt}}"
export WORLDARENA_BATCH_MODEL_CONFIG="${GEN3C_MODEL_CONFIG:-config/models/gen3c.yaml}"
export WORLDARENA_BATCH_MANIFEST="${GEN3C_MANIFEST:-${WORLDARENA_BATCH_MANIFEST:-artifacts/benchmark/manifest/worldarena_manifest_local_data_20260722.jsonl}}"
export WORLDARENA_BATCH_SUITES="${GEN3C_SUITES:-${WORLDARENA_BATCH_SUITES:-image_static}}"
export WORLDARENA_BATCH_OUTPUT_DIR="${GEN3C_OUTPUT_DIR:-${WORLDARENA_BATCH_OUTPUT_DIR:-$WORLD_ROOT/artifacts/predictions/gen3c-production}}"
export WORLDARENA_BATCH_TOTAL_GPUS="${GEN3C_TOTAL_GPUS:-${WORLDARENA_BATCH_TOTAL_GPUS:-8}}"
export WORLDARENA_BATCH_GPU_OFFSET="${GEN3C_GPU_OFFSET:-${WORLDARENA_BATCH_GPU_OFFSET:-0}}"
export WORLDARENA_BATCH_LIMIT="${GEN3C_LIMIT:-${WORLDARENA_BATCH_LIMIT:-}}"
export WORLDARENA_BATCH_DETACH="${GEN3C_DETACH:-${WORLDARENA_BATCH_DETACH:-1}}"
export WORLDARENA_BATCH_WAIT_FOR_GPUS="${GEN3C_WAIT_FOR_GPUS:-${WORLDARENA_BATCH_WAIT_FOR_GPUS:-0}}"

exec "$SCRIPT_DIR/launch_model_batch_8gpu.sh"
