#!/usr/bin/env bash
# ABot-World: eight one-GPU resident workers by default.
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
WORLD_ROOT="${WORLD_ROOT:-$(cd -- "$SCRIPT_DIR/.." && pwd)}"

export WORLDARENA_BATCH_MODEL_CONFIG="${ABOT_WORLD_MODEL_CONFIG:-config/models/abot_world.yaml}"
export WORLDARENA_BATCH_MANIFEST="${ABOT_WORLD_MANIFEST:-${WORLDARENA_BATCH_MANIFEST:-artifacts/benchmark/manifest/worldarena_manifest_local_data_20260722.jsonl}}"
export WORLDARENA_BATCH_SUITES="${ABOT_WORLD_SUITES:-${WORLDARENA_BATCH_SUITES:-image_static,image_dynamic}}"
export WORLDARENA_BATCH_OUTPUT_DIR="${ABOT_WORLD_OUTPUT_DIR:-${WORLDARENA_BATCH_OUTPUT_DIR:-$WORLD_ROOT/artifacts/predictions/abot-world-production}}"
export WORLDARENA_BATCH_TOTAL_GPUS="${ABOT_WORLD_TOTAL_GPUS:-${WORLDARENA_BATCH_TOTAL_GPUS:-8}}"
export WORLDARENA_BATCH_GPU_OFFSET="${ABOT_WORLD_GPU_OFFSET:-${WORLDARENA_BATCH_GPU_OFFSET:-0}}"
export WORLDARENA_BATCH_LIMIT="${ABOT_WORLD_LIMIT:-${WORLDARENA_BATCH_LIMIT:-}}"
export WORLDARENA_BATCH_DETACH="${ABOT_WORLD_DETACH:-${WORLDARENA_BATCH_DETACH:-1}}"
export WORLDARENA_BATCH_WAIT_FOR_GPUS="${ABOT_WORLD_WAIT_FOR_GPUS:-${WORLDARENA_BATCH_WAIT_FOR_GPUS:-0}}"

exec "$SCRIPT_DIR/launch_model_batch_8gpu.sh"
